-- Feriados nacionais:
CREATE TABLE stg_feriado (
    data         DATE         PRIMARY KEY,
    descricao    VARCHAR(60)  NOT NULL,
    tipo         VARCHAR(20)  NOT NULL,      
    origem_dado  VARCHAR(30)  NOT NULL      
);


/* 
   DIMENSÕES
*/

-- Tempo: grão = 1 hora 
CREATE TABLE dim_tempo (
    sk_tempo INTEGER PRIMARY KEY,   
    data_hora TIMESTAMP UNIQUE,        
    `data` DATE,
    ano SMALLINT,
    trimestre SMALLINT,
    mes SMALLINT,
    nome_mes VARCHAR(12),
    ano_mes CHAR(7),                   
    dia SMALLINT,
    dia_do_ano SMALLINT,
    semana_iso SMALLINT,
    dia_da_semana SMALLINT,                 
    nome_dia_semana VARCHAR(15),
    hora SMALLINT,                   
    faixa_horaria VARCHAR(10),                
    fim_de_semana BOOLEAN,
    feriado BOOLEAN,                    
    nome_feriado VARCHAR(60),
    tipo_feriado VARCHAR(20),
    ponto_facultativo BOOLEAN,
    dia_util BOOLEAN,                    
    estacao_ano VARCHAR(10),                
    periodo_hidrologico VARCHAR(8),                 
    patamar_carga VARCHAR(8)                  
);

-- Submercado: dimensão conformada (usada pelo PLD e pela geração)
CREATE TABLE dim_submercado (
    sk_submercado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_submercado CHAR(2) NOT NULL UNIQUE,    
    nome VARCHAR(40)  NOT NULL,
    regioes VARCHAR(80)  NOT NULL
);

-- Usina: SCD Tipo 2 em potência, situação e submercado; Tipo 1 nos demais atributos.
-- Fonte de energia fica achatada aqui (não há fato no grão)
CREATE TABLE dim_usina (
    sk_usina INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_usina VARCHAR(12) NOT NULL,      -- chave natural (negócio)
    nome VARCHAR(80) NOT NULL,
    cod_fonte VARCHAR(10),
    descricao_fonte VARCHAR(40),
    renovavel  BOOLEAN,
    intermitente BOOLEAN,
    cod_submercado CHAR(2),
    nome_submercado VARCHAR(40),
    uf CHAR(2),
    municipio VARCHAR(60),
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    potencia_mw NUMERIC(8,2),              
    data_inicio_operacao DATE,                     
    situacao VARCHAR(20),
    lat_clima NUMERIC(9,6),
    lon_clima NUMERIC(9,6),
    lat_grade_clima NUMERIC(9,6),
    lon_grade_clima NUMERIC(9,6),
    elevacao_m NUMERIC(7,1),
    criterio_ponto_clima VARCHAR(30),
    flags_qualidade TEXT,
    dt_inicio_vigencia DATE NOT NULL,
    dt_fim_vigencia DATE NOT NULL,
    registro_atual BOOLEAN NOT NULL,
    carregado_em TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_dim_usina_atual ON dim_usina (cod_usina) WHERE registro_atual;
CREATE UNIQUE INDEX uk_dim_usina_vigencia ON dim_usina (cod_usina, dt_inicio_vigencia);

CREATE TABLE dim_tipo_parada (
    sk_tipo_parada INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipoVARCHAR(20) NOT NULL UNIQUE,    -- Programada | Forçada
    descricao VARCHAR(60)
);

CREATE TABLE dim_origem_dado (
    sk_origem_dado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem VARCHAR(20) NOT NULL UNIQUE,
    automatica BOOLEAN
);


/* 
TABELAS FATO 
*/

/* GRÃO: 1 usina x 1 hora, para cada hora com medição válida na camada tratada.
   Medidas: energia_mwh (aditiva, pode ser nula), disponibilidade_mw (não aditiva),
   capacidade_mwh = potência vigente x 1 h (aditiva; denominador do fator de capacidade). */
CREATE TABLE fato_geracao_horaria (
    sk_tempo INTEGER NOT NULL REFERENCES dim_tempo (sk_tempo),
    sk_usina INTEGER NOT NULL REFERENCES dim_usina (sk_usina),
    sk_submercado INTEGER NOT NULL REFERENCES dim_submercado (sk_submercado),
    sk_origem_dado INTEGER NOT NULL REFERENCES dim_origem_dado (sk_origem_dado),
    id_medicao_origem BIGINT  NOT NULL,
    energia_mwh NUMERIC(12,3),
    energia_mwh_original NUMERIC(12,3),
    disponibilidade_mw NUMERIC(8,2),
    capacidade_mwh NUMERIC(10,2),
    recebido_em TIMESTAMP,
    atraso_recebimento_min INTEGER,
    flag_energia_ausente BOOLEAN NOT NULL,
    flag_valor_corrigido BOOLEAN NOT NULL,
    flag_recebimento_atrasado BOOLEAN NOT NULL,
    flag_recebido_antes_do_fato BOOLEAN NOT NULL,
    flags_qualidade TEXT,
    PRIMARY KEY (sk_tempo, sk_usina)
);
CREATE INDEX ix_fato_geracao_usina_tempo ON fato_geracao_horaria (sk_usina, sk_tempo);
CREATE INDEX ix_fato_geracao_submercado  ON fato_geracao_horaria (sk_submercado, sk_tempo);

/* GRÃO: 1 submercado x 1 hora (PLD horário da CCEE, 2025 em diante).
   Medida: pld_rs_mwh (NÃO aditiva: use média ou ponderação por energia). */
CREATE TABLE fato_pld_horario (
    sk_tempo INTEGER NOT NULL REFERENCES dim_tempo (sk_tempo),
    sk_submercado INTEGER NOT NULL REFERENCES dim_submercado (sk_submercado),
    pld_rs_mwh NUMERIC(10,2) NOT NULL,
    PRIMARY KEY (sk_tempo, sk_submercado)
);

/* GRÃO: 1 ponto de clima (a usina) x 1 hora (Open-Meteo, grade ERA5).
   Medidas: todas não aditivas (use média, máximo ou soma só de precipitação). */
CREATE TABLE fato_clima_horario (
    sk_tempo INTEGER NOT NULL REFERENCES dim_tempo (sk_tempo),
    sk_usina INTEGER NOT NULL REFERENCES dim_usina (sk_usina),
    sk_submercado INTEGER NOT NULL REFERENCES dim_submercado (sk_submercado),
    temperatura_c NUMERIC(5,2),
    precipitacao_mm NUMERIC(6,2),
    cobertura_nuvens_pct SMALLINT,
    radiacao_w_m2 NUMERIC(7,2),
    vento_10m_ms NUMERIC(5,2),
    vento_100m_ms NUMERIC(5,2),
    dir_vento_100m_graus SMALLINT,
    PRIMARY KEY (sk_tempo, sk_usina)
);
CREATE INDEX ix_fato_clima_usina_tempo ON fato_clima_horario (sk_usina, sk_tempo);

/* GRÃO: 1 usina x 1 hora coberta por uma parada registrada e válida.
   Se duas paradas cobrirem a mesma hora, vale a de menor id_parada.
   Medidas: horas_indisponiveis (aditiva, sempre 1), energia_nao_gerada_estimada_mwh
   (aditiva; mediana da mesma hora do dia na janela de +-14 dias, fora de paradas),
   pld_rs_mwh (não aditiva), receita_nao_gerada_estimada_rs (aditiva). */
CREATE TABLE fato_indisponibilidade_horaria (
    sk_tempo INTEGER NOT NULL REFERENCES dim_tempo (sk_tempo),
    sk_usina INTEGER NOT NULL REFERENCES dim_usina (sk_usina),
    sk_submercado INTEGER NOT NULL REFERENCES dim_submercado (sk_submercado),
    sk_tipo_parada INTEGER NOT NULL REFERENCES dim_tipo_parada (sk_tipo_parada),
    id_parada_origem INTEGER NOT NULL,
    motivo VARCHAR(120),
    horas_indisponiveis SMALLINT NOT NULL DEFAULT 1,
    energia_nao_gerada_estimada_mwh NUMERIC(12,3),
    n_horas_referencia SMALLINT,
    tem_referencia BOOLEAN NOT NULL,
    pld_rs_mwh NUMERIC(10,2),
    receita_nao_gerada_estimada_rs  NUMERIC(14,2),
    PRIMARY KEY (sk_tempo, sk_usina)
);

/* GRÃO: 1 regra de qualidade x 1 fase (ANTES | DEPOIS), da execução mais recente de cada fase. */
CREATE TABLE fato_qualidade_regra (
    fase VARCHAR(10) NOT NULL,
    id_regra VARCHAR(6) NOT NULL,
    id_execucao INTEGER NOT NULL,
    regra VARCHAR(160) NOT NULL,
    dimensao_qualidade VARCHAR(30) NOT NULL,
    tabela VARCHAR(60) NOT NULL,
    registros_avaliados BIGINT,
    registros_falha BIGINT,
    percentual_falha NUMERIC(9,4),
    decisao VARCHAR(14),
    executado_em TIMESTAMPTZ,
    PRIMARY KEY (fase, id_regra)
);

/* GRÃO: 1 indicador de negócio x 1 nível (total | fonte | usina) x 1 chave, comparando antes e depois da limpeza. */
CREATE TABLE fato_impacto_limpeza (
    nivel VARCHAR(10) NOT NULL,
    chave VARCHAR(40) NOT NULL,
    indicador VARCHAR(30) NOT NULL,
    antes DOUBLE PRECISION,
    depois DOUBLE PRECISION,
    delta DOUBLE PRECISION,
    delta_pct DOUBLE PRECISION,
    PRIMARY KEY (nivel, chave, indicador)
);


/* 
   VIEWS PARA O PAINEL
*/

CREATE VIEW vw_dim_usina_atual AS
SELECT * FROM dim_usina WHERE registro_atual AND sk_usina > 0;

-- Receita valorada ao PLD = energia da hora x PLD da hora no submercado da usina
CREATE VIEW vw_geracao_valorada AS
SELECT g.sk_tempo, g.sk_usina, g.sk_submercado,
       g.energia_mwh, g.capacidade_mwh,
       p.pld_rs_mwh,
       g.energia_mwh * p.pld_rs_mwh AS receita_rs
FROM fato_geracao_horaria g
LEFT JOIN fato_pld_horario p
       ON p.sk_tempo = g.sk_tempo AND p.sk_submercado = g.sk_submercado;

-- Índice de qualidade: média simples do % de acerto das regras (100 = sem falhas)
CREATE VIEW vw_indice_qualidade AS
SELECT fase, dimensao_qualidade, tabela,
       COUNT(*) AS regras,
       ROUND(AVG(100 - percentual_falha), 2) AS indice_qualidade_pct
FROM fato_qualidade_regra
WHERE registros_avaliados > 0
GROUP BY fase, dimensao_qualidade, tabela;
